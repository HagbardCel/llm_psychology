def _sha256_file(path: Path) -> tuple[int, str]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(65536)
            if not chunk:
                break
            size += len(chunk)
            digest.update(chunk)
    return size, digest.hexdigest()


def _immutable_manifest_lines(run_dir: Path) -> list[str]:
    lines = [
        "## Section E — Immutable artifact manifest",
        "",
        "| Artifact | Purpose | Size | SHA-256 |",
        "| --- | --- | ---: | --- |",
    ]
    entries = [
        (run_dir / "runtime" / "trace.jsonl", "Diagnostics"),
        (run_dir / "runtime" / "db_snapshot.sqlite", "Final DB"),
        (run_dir / "transcript.md", "Patient-visible dialogue"),
    ]
    checkpoints = run_dir / "checkpoints"
    if checkpoints.is_dir():
        for checkpoint in sorted(checkpoints.glob("*.sqlite")):
            entries.append((checkpoint, "Checkpoint"))
    for path, purpose in entries:
        if path.is_file():
            size, digest = _sha256_file(path)
            rel = path.relative_to(run_dir)
            lines.append(f"| `{rel}` | {purpose} | {size} | `{digest}` |")
    lines.extend(
        [
            "",
            "Post-audit artifacts (not hashed as final bytes): `run.json`, "
            "`journey.jsonl` (terminal event appended after audit render).",
            "",
        ]
    )
    return lines


