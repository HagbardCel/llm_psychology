_CONTEXT_DATA_RE = re.compile(
    r"<context_data>\n(?P<body>.*?)\n</context_data>",
    flags=re.DOTALL,
)


@dataclass(frozen=True, slots=True)
class JourneyEvent:
    sequence: int
    timestamp: str
    kind: str
    context: dict[str, Any]
    data: dict[str, Any]


@dataclass(frozen=True, slots=True)
class AuditFinding:
    code: str
    message: str
    evidence: dict[str, Any] = field(default_factory=dict)


@dataclass
class AuditResult:
    findings: list[AuditFinding] = field(default_factory=list)
    warnings: list[AuditFinding] = field(default_factory=list)
    not_applicable: list[AuditFinding] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.findings

    def fail(self, code: str, message: str, **evidence: Any) -> None:
        self.findings.append(
            AuditFinding(code=code, message=message, evidence=evidence)
        )

    def warn(self, code: str, message: str, **evidence: Any) -> None:
        self.warnings.append(
            AuditFinding(code=code, message=message, evidence=evidence)
        )

    def na(self, code: str, message: str, **evidence: Any) -> None:
        self.not_applicable.append(
            AuditFinding(code=code, message=message, evidence=evidence)
        )


@dataclass(frozen=True, slots=True)
class StructuredCallReconstruction:
    llm_call_id: str
    model: str | None
    accepted_result: Mapping[str, Any]
    accepted_sequence: int


class JourneyLog:
    """Append-only journey.jsonl with fixed five-field envelope."""

    def __init__(self, path: Path) -> None:
        self._path = path
        self._sequence = 0
        self._path.parent.mkdir(parents=True, exist_ok=True)
        if not self._path.exists():
            with open_private_file(self._path, mode="w"):
                pass

    def append(
        self,
        kind: str,
        *,
        context: Mapping[str, Any] | None = None,
        data: Mapping[str, Any] | None = None,
    ) -> JourneyEvent:
        self._sequence += 1
        event = JourneyEvent(
            sequence=self._sequence,
            timestamp=datetime.now(UTC).isoformat().replace("+00:00", "Z"),
            kind=kind,
            context=dict(context or {}),
            data=dict(data or {}),
        )
        line = json.dumps(
            {
                "sequence": event.sequence,
                "timestamp": event.timestamp,
                "kind": event.kind,
                "context": event.context,
                "data": event.data,
            },
            ensure_ascii=False,
            separators=(",", ":"),
        )
        with open_private_file(self._path, mode="a") as handle:
            handle.write(line + "\n")
        return event


def _allocation_stamp() -> str:
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")


def _allocation_suffix() -> str:
    return uuid.uuid4().hex[:8]


def _mkdir_exclusive_private(path: Path) -> None:
    """Create ``path`` exclusively with mode ``0700``."""
    path.mkdir(parents=True, exist_ok=False, mode=0o700)
    try:
        os.chmod(path, 0o700)
    except OSError:
        pass


def _mkdir_private_child(path: Path) -> None:
    path.mkdir(mode=0o700)
    try:
        os.chmod(path, 0o700)
    except OSError:
        pass


def _prepare_run_directory(run_dir: Path) -> Path:
    _mkdir_exclusive_private(run_dir)
    _mkdir_private_child(run_dir / "data")
    _mkdir_private_child(run_dir / "checkpoints")
    return run_dir


def allocate_run_directory(output_dir: Path | None = None) -> Path:
    """Create an exclusive run directory with private permissions."""
    if output_dir is not None:
        run_dir = Path(output_dir)
        if run_dir.exists():
            raise FileExistsError(
                f"simulation output directory already exists: {run_dir}"
            )
        return _prepare_run_directory(run_dir)

    stamp = _allocation_stamp()
    while True:
        candidate = Path("logs") / "simulations" / f"run-{stamp}-{_allocation_suffix()}"
        try:
            return _prepare_run_directory(candidate)
        except FileExistsError:
            continue


